private const val GITHUB_LOGIN_PATH = "/auth/github/login"
private const val GITHUB_CALLBACK_PATH = "/auth/github/callback"
private const val GITHUB_STATE_COOKIE_NAME = "__Host-Http-github-state"
private const val GITHUB_CODE_VERIFIER_COOKIE_NAME = "__Host-Http-github-code-verifier"
private const val SESSION_COOKIE_NAME = "__Host-Http-session"

private const val CLIENT_ID = "test-client-id"
private const val CLIENT_SECRET = "test-client-secret"
private const val LOGIN_COOKIE_MAX_AGE_SECONDS = 600L
private const val REDIRECT_URI = "https://example.com/auth/github/callback"
private const val VALID_STATE = "test-state"
private const val VALID_CODE_VERIFIER = "test-code-verifier"
private const val VALID_CODE = "valid-code"
private const val SESSION_LIFETIME = "1h"
private const val SESSION_LIFETIME_SECONDS = 3600L

class AuthnServerTest {
    @ParameterizedTest
    @ValueSource(strings = [GITHUB_LOGIN_PATH, GITHUB_CALLBACK_PATH])
    fun `responses are not cacheable`(path: String) {
        val response = request(path)

        assertEquals("no-store", response.header(HttpHeaders.CACHE_CONTROL.toString()))
    }

    @ParameterizedTest
    @ValueSource(strings = [GITHUB_LOGIN_PATH, GITHUB_CALLBACK_PATH])
    fun `non-GET request is rejected`(path: String) {
        val response = request(path, method = Method.POST)

        assertEquals(HttpResponseStatus.METHOD_NOT_ALLOWED.code(), response.statusCode)
        assertEquals("GET", response.header(HttpHeaders.ALLOW.toString()))
    }

    @Test
    fun `GitHub login redirects to GitHub authorization with correct URL params and cookies`() {
        val response = request(GITHUB_LOGIN_PATH)
        val location = response.header(HttpHeaders.LOCATION.toString())?.let(::QueryStringDecoder)

        val expectedState = "YLQguzhR2dR6y5M9vnA5mw"
        // Status code
        assertEquals(HttpResponseStatus.FOUND.code(), response.statusCode)
        // Location header
        assertNotNull(location)
        assertEquals("$githubOrigin/login/oauth/authorize", location.path())
        // URL parameters
        assertEquals(
            mapOf(
                "client_id" to CLIENT_ID,
                "redirect_uri" to REDIRECT_URI,
                // state and code_challenge are generated by DeterministicRandomSource
                "state" to expectedState,
                "code_challenge" to "vx_gXmI6Rukxbi2vUqMVw0vkXK0urEDTCKCFjZAzdVM",
                "code_challenge_method" to "S256",
                // Required by https://datatracker.ietf.org/doc/html/rfc6749#section-4.1.1
                "response_type" to "code",
            ),
            location.parameters().mapValues { it.value.single() },
        )
        // Cookies
        assertEquals(
            hostHttpCookieBuilder(GITHUB_STATE_COOKIE_NAME, expectedState)
                .setSameSite("Lax")
                .setMaxAge(LOGIN_COOKIE_MAX_AGE_SECONDS)
                .build(),
            response.detailedCookie(GITHUB_STATE_COOKIE_NAME),
        )
        assertEquals(
            // Generated by DeterministicRandomSource
            hostHttpCookieBuilder(
                GITHUB_CODE_VERIFIER_COOKIE_NAME,
                "9sktozrwHU-3cOmMAyX0HT66-JhtpxLIK81NVUvwtUA",
            )
                .setSameSite("Lax")
                .setMaxAge(LOGIN_COOKIE_MAX_AGE_SECONDS)
                .build(),
            response.detailedCookie(GITHUB_CODE_VERIFIER_COOKIE_NAME),
        )
    }

    @Test
    fun `GitHub callback clears login cookies`() {
        val response = request(
            GITHUB_CALLBACK_PATH,
            GITHUB_STATE_COOKIE_NAME to "some-state",
            GITHUB_CODE_VERIFIER_COOKIE_NAME to "some-code-verifier",
        )

        for (name in listOf(GITHUB_STATE_COOKIE_NAME, GITHUB_CODE_VERIFIER_COOKIE_NAME)) {
            assertEquals(
                hostHttpCookieBuilder(name, "")
                    .setSameSite("Lax")
                    .setMaxAge(0)
                    .build(),
                response.detailedCookie(name),
            )
        }
    }

    @Test
    fun `GitHub callback with valid code, state, and code verifier sets session cookie and redirects to correct route`() {
        val response = request(
            "$GITHUB_CALLBACK_PATH?code=$VALID_CODE&state=$VALID_STATE",
            GITHUB_STATE_COOKIE_NAME to VALID_STATE,
            GITHUB_CODE_VERIFIER_COOKIE_NAME to VALID_CODE_VERIFIER,
        )

        // Session cookie
        assertEquals(
            // Generated by DeterministicRandomSource
            hostHttpCookieBuilder(SESSION_COOKIE_NAME, "s_2wTa5P82Lwqd50UvNyQRad")
                .setSameSite("Strict")
                .setMaxAge(SESSION_LIFETIME_SECONDS)
                .build(),
            response.detailedCookie(SESSION_COOKIE_NAME),
        )
        // Redirect
        assertEquals(HttpResponseStatus.FOUND.code(), response.statusCode)
        assertEquals("/", response.header(HttpHeaders.LOCATION.toString()))
    }

    @Test
    fun `GitHub callback without state cookie is rejected as bad request`() {
        val response = request(
            "$GITHUB_CALLBACK_PATH?code=$VALID_CODE&state=$VALID_STATE",
            GITHUB_CODE_VERIFIER_COOKIE_NAME to VALID_CODE_VERIFIER,
        )

        assertEquals(HttpResponseStatus.BAD_REQUEST.code(), response.statusCode)
    }

    @Test
    fun `GitHub callback without code verifier cookie is rejected as bad request`() {
        val response = request(
            "$GITHUB_CALLBACK_PATH?code=$VALID_CODE&state=$VALID_STATE",
            GITHUB_STATE_COOKIE_NAME to VALID_STATE,
        )

        assertEquals(HttpResponseStatus.BAD_REQUEST.code(), response.statusCode)
    }

    @Test
    fun `GitHub callback without state param is rejected`() {
        val response = request(
            "$GITHUB_CALLBACK_PATH?code=$VALID_CODE",
            GITHUB_STATE_COOKIE_NAME to VALID_STATE,
            GITHUB_CODE_VERIFIER_COOKIE_NAME to VALID_CODE_VERIFIER,
