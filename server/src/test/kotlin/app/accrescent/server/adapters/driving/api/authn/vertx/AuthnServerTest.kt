    @Test
    fun `request for unknown path is not found`() {
        val response = request("/auth/unknown/login")

        assertEquals(HttpResponseStatus.NOT_FOUND.code(), response.statusCode)
    }

    private lateinit var githubServer: HttpServer
    private lateinit var githubOrigin: String
    private lateinit var dataStore: MemoryDataStore
    private lateinit var server: HttpServer

    @BeforeEach
    fun startServers() {
        githubServer = vertx.createHttpServer()
            .requestHandler(::handleGithubRequest)
            .listen(0, "localhost")
            .await()
        githubOrigin = "http://localhost:${githubServer.actualPort()}"

        dataStore = MemoryDataStore(vertx)
        dataStore.migrateToHead().unwrap()
        server = startAuthnServer(
            AuthenticationApiImpl(
                dataStore = dataStore,
                idGenerator = IdGenerator(DeterministicRandomSource()),
                sessionLifetime = SessionLifetime.parse(SESSION_LIFETIME).unwrap(),
                timestampSource = FixedTimestampSource(),
            ),
        )
    }

    /**
     * Starts an HTTP server serving an [AuthnServer] which uses the stub GitHub server.
     *
     * @param authenticationApi the authentication API for the [AuthnServer] to use.
     * @return the started HTTP server.
     */
    private fun startAuthnServer(authenticationApi: AuthenticationApi): HttpServer {
        val authnServer = AuthnServer(
            vertx = vertx,
            context = vertx.dispatcher(),
            authnConfig = AuthnConfig(
                github = GithubAuthnConfig(
                    clientId = NonEmptyString.fromString(CLIENT_ID).unwrap(),
                    clientSecret = NonEmptyString.fromString(CLIENT_SECRET).unwrap(),
                    redirectUri = HttpUri.fromString(REDIRECT_URI).unwrap(),
                ),
                session = SessionConfig(
                    lifetime = SessionLifetime.parse(SESSION_LIFETIME).unwrap(),
                ),
            ),
            authenticationApi = authenticationApi,
            randomSource = DeterministicRandomSource(),
            githubSite = "$githubOrigin/login",
            githubUserInfoPath = "$githubOrigin/user",
        )

        return vertx.createHttpServer()
            .requestHandler(authnServer)
            .listen(0, "localhost")
            .await()
    }

    @AfterEach
    fun stopServers() {
        server.close().await()
        dataStore.close().unwrap()
        githubServer.close().await()
    }

    /**
     * Makes a request to the auth server.
     *
     * @param pathAndQuery the path and query of the request URI.
     * @param cookies the (name, value) pairs of cookies to send.
     * @param method the HTTP method of the request.
     * @return the response.
     */
    private fun request(
        pathAndQuery: String,
        vararg cookies: Pair<String, String>,
        method: Method = Method.GET,
    ): Response {
        return given()
            .redirects().follow(false)
            .cookies(cookies.toMap())
            .request(method, "http://localhost:${server.actualPort()}$pathAndQuery")
    }

    private companion object {
        private val vertx = Vertx.vertx()

        @AfterAll
        @JvmStatic
        fun closeVertx() {
            vertx.close().await()
        }

        private val CLIENT_AUTHORIZATION =
            "Basic ${Base64.encode("$CLIENT_ID:$CLIENT_SECRET".toByteArray())}"

        /**
         * Handles requests to the stub GitHub server.
         *
         * The token endpoint only issues an access token for [VALID_CODE] with [VALID_CODE_VERIFIER],
         * [REDIRECT_URI], and the expected client credentials (sent via HTTP Basic authentication), and the user
         * endpoint only accepts that access token.
         */
        private fun handleGithubRequest(request: HttpServerRequest) {
            val response = request.response().putHeader(HttpHeaders.CONTENT_TYPE, "application/json")

            val fakeAccessToken = "test-access-token"
            val path: String? = request.path()
            when (path) {
                "/login/oauth/access_token" -> request.body().onSuccess { body ->
                    val params = QueryStringDecoder(body.toString(), false)
                        .parameters()
                        .mapValues { it.value.single() }
                    val expectedParams = mapOf(
                        "code" to VALID_CODE,
                        "code_verifier" to VALID_CODE_VERIFIER,
                        "grant_type" to "authorization_code",
                        "redirect_uri" to REDIRECT_URI,
                    )
                    val responseBody = if (
                        request.getHeader(HttpHeaders.AUTHORIZATION) == CLIENT_AUTHORIZATION
                        && params == expectedParams
                    ) {
                        JsonObject().put("access_token", fakeAccessToken).put("token_type", "bearer")
                    } else {
                        JsonObject().put("error", "bad_verification_code")
                    }
                    response.end(responseBody.encode())
                }

                "/user" -> if (request.getHeader(HttpHeaders.AUTHORIZATION) == "Bearer $fakeAccessToken") {
                    // Arbitrary GitHub user ID - just needs to fit into a Long
                    response.end(JsonObject().put("id", 12345).encode())
                } else {
                    response.setStatusCode(HttpResponseStatus.UNAUTHORIZED.code()).end()
                }

                else -> response.setStatusCode(HttpResponseStatus.NOT_FOUND.code()).end()
            }
        }
    }
}

/**
 * Creates a cookie builder with the attributes required by the `__Host-Http-` cookie name
 * prefix.
 *
 * @param name the cookie name.
 * @param value the cookie value.
 * @return a builder with Path set to "/", Secure set, and HttpOnly set.
 */
private fun hostHttpCookieBuilder(name: String, value: String): Cookie.Builder {
    return Cookie.Builder(name, value)
        .setPath("/")
        .setSecured(true)
        .setHttpOnly(true)
}
