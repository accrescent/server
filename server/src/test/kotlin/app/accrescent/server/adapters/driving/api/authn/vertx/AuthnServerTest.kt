    @Test
    fun `GitHub callback with access denied error redirects to correct route`() {
        val response = request(
            "$GITHUB_CALLBACK_PATH?error=access_denied&state=$VALID_STATE",
            GITHUB_STATE_COOKIE_NAME to VALID_STATE,
            GITHUB_CODE_VERIFIER_COOKIE_NAME to VALID_CODE_VERIFIER,
